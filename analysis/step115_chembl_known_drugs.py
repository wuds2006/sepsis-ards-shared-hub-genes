#!/usr/bin/env python3
"""
Step 115 -- ChEMBL known-drugs query for the six hub genes (provenance closure).

Reproduces 09_docking_drug/chembl_known_drugs.csv, originally generated by an
ad-hoc query on 2026-09-17 against the live EBI ChEMBL web services
(ChEMBL release 37, May 2026). This script was written on 2026-10-21 to close
the archiving gap; release 37 was still the live release at that date, so the
re-run should match the archived CSV.

Method: for each gene symbol, search the ChEMBL target endpoint for a human
SINGLE PROTEIN target, then collect all mechanisms of action recorded for that
target. n_drugs = distinct molecules with a mechanism of action; max_phase =
highest clinical phase among them; top_drugs = up to five names by phase.

Output columns (identical to the archived file):
  gene, chembl_target, n_drugs, max_phase, top_drugs
"""
import csv, json, subprocess, sys, time

BASE = "https://www.ebi.ac.uk/chembl/api/data"
GENES = ["CDK5RAP2", "CD177", "GRB10", "UPP1", "EXOSC4", "VNN1"]
OUT = "09_docking_drug/chembl_known_drugs.csv"


def get(url):
    r = subprocess.run(["curl", "-s", "-m", "60", url], capture_output=True, text=True)
    return json.loads(r.stdout)


def find_target(symbol):
    """Return CHEMBL target id for the human single-protein target, or ''."""
    data = get(f"{BASE}/target/search.json?q={symbol}")
    for hit in data.get("targets", []):
        if hit.get("target_type") == "SINGLE PROTEIN" and hit.get("organism") == "Homo sapiens":
            comps = hit.get("target_components") or []
            for c in comps:
                syns = (c.get("target_component_synonyms") or [])
                if any(s.get("component_synonym", "").upper() == symbol.upper()
                       and s.get("syn_type") == "GENE_SYMBOL" for s in syns):
                    return hit["target_chembl_id"]
    # fallback: first human single-protein hit
    for hit in data.get("targets", []):
        if hit.get("target_type") == "SINGLE PROTEIN" and hit.get("organism") == "Homo sapiens":
            return hit["target_chembl_id"]
    return ""


def known_drugs(target_id):
    """Return (n_distinct_molecules, max_phase, top_names) from MoA records."""
    mols, url = {}, f"{BASE}/mechanism.json?target_chembl_id={target_id}&limit=1000"
    while url:
        data = get(url)
        for m in data.get("mechanisms", []):
            mid = m.get("molecule_chembl_id")
            if mid:
                mols[mid] = max(mols.get(mid, 0), m.get("max_phase") or 0)
        url = data.get("page_meta", {}).get("next")
    if not mols:
        return 0, 0, ""
    ids = ",".join(mols)
    names = {}
    data = get(f"{BASE}/molecule.json?molecule_chembl_id__in={ids}&limit=1000")
    for d in data.get("molecules", []):
        names[d["molecule_chembl_id"]] = d.get("pref_name") or d["molecule_chembl_id"]
    ranked = sorted(mols.items(), key=lambda kv: -kv[1])
    top = "; ".join(f"{names.get(mid, mid)} (phase {ph})" for mid, ph in ranked[:5])
    return len(mols), max(mols.values()), top


def main():
    rows = []
    for g in GENES:
        tid = find_target(g)
        time.sleep(0.4)
        if tid:
            n, ph, top = known_drugs(tid)
        else:
            n, ph, top = 0, 0, ""
        rows.append({"gene": g, "chembl_target": tid, "n_drugs": n,
                     "max_phase": ph, "top_drugs": top})
        print(f"{g:10s} target={tid or '-':14s} n_drugs={n} max_phase={ph}")
        time.sleep(0.4)
    with open(OUT, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["gene", "chembl_target", "n_drugs",
                                          "max_phase", "top_drugs"])
        w.writeheader()
        w.writerows(rows)
    print("wrote", OUT)


if __name__ == "__main__":
    sys.exit(main())
